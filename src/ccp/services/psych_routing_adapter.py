def _build_v1_constraint(profile: EmotionalDNAProfile) -> list[str]:
    """V1 — Trigger Specificity Threshold constraint."""
    v1 = profile.appraisal_variables.v1_trigger_specificity_threshold
    score = v1.score
    if score >= 8:
        level = "HIGH SPECIFICITY"
        guidance = (
            "Ground every claim in concrete, specific situations. "
            "Abstract generalisations will not land — this audience processes "
            "through precise, identifiable moments."
        )
    elif score >= 5:
        level = "MID SPECIFICITY"
        guidance = (
            "Balance concrete examples with broader pattern recognition. "
            "Use specific anchors but connect them to general mechanisms."
        )
    else:
        level = "LOW SPECIFICITY"
        guidance = (
            "This audience processes at the pattern level. Use archetypes "
            "and general principles. Hyper-specific examples may feel alienating."
        )

    return [
        f"CONSTRAINT (V1 — Trigger Specificity, score={score}/10 [{level}]): "
        f"{guidance}"
    ]


def _build_v2_constraint(profile: EmotionalDNAProfile) -> list[str]:
    """V2 — Appraisal Sequence Ordering constraint."""
    v2 = profile.appraisal_variables.v2_appraisal_sequence_ordering
    ordering = v2.type.value if v2.type else "mixed"
    mapping = {
        "mechanism_first": (
            "Lead with the mechanism — explain HOW the wound/trigger works before "
            "invoking the emotional response. Logic precedes feeling for this coach."
        ),
        "moral_verdict_first": (
            "Lead with the moral verdict — name what was wrong or unfair before "
            "explaining the mechanism. Justice-orientation drives the framing."
        ),
        "narrative_first": (
            "Lead with the story — establish the narrative arc before introducing "
            "the analytical insight. Emotional transportation precedes understanding."
        ),
        "coping_first": (
            "Lead with the coping frame — establish that recovery is possible before "
            "engaging the wound. Hope-anchoring must precede the descent."
        ),
        "mixed": (
            "Appraisal sequence is context-dependent — follow the archetype's "
            "natural structural requirements rather than a fixed ordering rule."
        ),
    }
    guidance = mapping.get(ordering, f"Appraisal ordering = {ordering}.")
    return [
        f"CONSTRAINT (V2 — Appraisal Sequence [{ordering}]): {guidance}"
    ]


def _build_v3_constraint(profile: EmotionalDNAProfile) -> list[str]:
    """V3 — Coping Potential Pattern constraint."""
    v3 = profile.appraisal_variables.v3_coping_potential_pattern
    ratio = v3.ratio if v3.ratio is not None else 0.5
    if ratio >= 0.7:
        guidance = (
            "HIGH coping potential ratio — always close with actionable resolution. "
            "This coach's audience expects agency and forward momentum. "
            "Do not leave content in the wound without a clear coping pathway."
        )
    elif ratio >= 0.4:
        guidance = (
            "MODERATE coping potential — balance wound acknowledgement with "
            "resolution. Not every piece needs a full action plan, but "
            "forward movement must be implied."
        )
    else:
        guidance = (
            "LOW coping potential ratio — this coach works in the wound longer "
            "before offering resolution. Do not rush to fix. "
            "Validation and witnessing are the primary function here."
        )

    return [
        f"CONSTRAINT (V3 — Coping Potential, ratio={ratio:.2f}): {guidance}"
    ]


