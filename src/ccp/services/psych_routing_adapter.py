def _build_routing_brief_constraints(brief: PsychRoutingBrief) -> list[str]:
    """Build Block B constraint strings from DEP-ENG-016 PsychRoutingBrief variables."""
    pc = brief.psychological_classification
    constraints: list[str] = [
        f"PSYCH ROUTING (FR18 DEP-ENG-016 — routing_id={brief.routing_id}):",
        f"CONSTRAINT: mood_state_primary = <{pc.mood_state_primary.value}>. "
        f"Structure the content's emotional purpose to serve this primary need.",
        f"CONSTRAINT: arousal_direction = <{pc.arousal_direction.value}>. "
        f"The content must move the audience's arousal in this direction.",
        f"CONSTRAINT: valence_delivery = <{pc.valence_delivery.value}>. "
        f"Emotional atmosphere must match this polarity.",
        f"CONSTRAINT: regulatory_frame = <{pc.regulatory_frame.value}>. "
        f"Frame outcomes through this regulatory lens (promotion vs prevention).",
        f"CONSTRAINT: sdt_need_primary = <{pc.sdt_need_primary.value}>. "
        f"The content's core psychological function must satisfy this SDT need.",
    ]

    if pc.sequencing_dependency.value != "independent":
        constraints.append(
            f"CONSTRAINT: sequencing_dependency = <{pc.sequencing_dependency.value}>. "
            f"This content requires positive affect priming before deployment."
        )

    if pc.comparison_type.value != "none":
        constraints.append(
            f"CONSTRAINT: comparison_type = <{pc.comparison_type.value}>. "
            f"Social comparison mechanics must be structured to this type."
        )

    if pc.tmt_function.value != "none":
        constraints.append(
            f"CONSTRAINT: tmt_function = <{pc.tmt_function.value}>. "
            f"Terror Management Theory function — must match worldview engagement type."
        )

    # Payload masking instruction (Trojan Horse structural behaviour)
    if brief.payload_masking_instruction:
        constraints.append(
            f"PAYLOAD MASKING (FR18 Trojan Horse): {brief.payload_masking_instruction}"
        )

    if brief.is_fallback and brief.operator_warning:
        constraints.append(
            f"[OPERATOR WARNING — FALLBACK BRIEF]: {brief.operator_warning}"
        )

    return constraints


# ─── Adapter ─────────────────────────────────────────────────────────────────

class PsychRoutingAdapter:
    """Adapter-4 — Loads DEP-LIB-001 + DEP-ENG-016 into SKILL.md Block B.

    Injects:
        - V1-V5 appraisal variable constraints
        - V6-V10 MFQ-2 moral foundation directives
        - CSIP v3 ceiling/floor/suppression constraints
        - PsychRoutingBrief (DEP-ENG-016) 8-variable resolved routing block
        - Rhythm instructions (ALL bypass_c08=True — FR8 C-08 whitelist mandate)

    The routing brief (DEP-ENG-016) is optional — if not provided, only
    emotional DNA constraints are injected (no routing brief warnings).

    ADR-01: coach_id in all outputs and receipt logs.
    C-08 MANDATE: All RhythmInstruction objects carry bypass_c08=True. This is
        structural law from FR8 and cannot be overridden by callers.
    """

    def __init__(self, receipt_chain: ReceiptChain) -> None:
        self._rc = receipt_chain

    def load(
        self,
        emotional_dna: EmotionalDNAProfile,
        coach_id: str,
        routing_brief: PsychRoutingBrief | None = None,
    ) -> AdapterRunResult:
        """Execute the Emotional DNA + Routing Brief → Block B injection.

        Args:
            emotional_dna: Validated DEP-LIB-001 EmotionalDNAProfile.
            coach_id: ADR-01 coach instance identifier.
            routing_brief: Optional DEP-ENG-016 PsychRoutingBrief. If provided,
                adds 8-variable routing constraints and payload masking instruction.

        Returns:
            AdapterRunResult with Block B injection payload on success.
        """
        constraints: list[str] = []

        # ── V1-V5 Appraisal Variable Constraints ──────────────────────────────
        constraints.extend(_build_v1_constraint(emotional_dna))
        constraints.extend(_build_v2_constraint(emotional_dna))
        constraints.extend(_build_v3_constraint(emotional_dna))
        constraints.extend(_build_v4_constraint(emotional_dna))
        constraints.extend(_build_v5_constraint(emotional_dna))

        # ── V6-V10 Moral Foundation Directives ────────────────────────────────
        moral_constraints = _build_moral_foundation_constraints(emotional_dna)
        constraints.extend(moral_constraints)

        # ── CSIP v3 Extension Constraints ─────────────────────────────────────
        csip_constraints = _build_csip_constraints(emotional_dna)
        constraints.extend(csip_constraints)

        # ── Routing Brief Constraints (if provided) ────────────────────────────
        if routing_brief:
            constraints.extend(_build_routing_brief_constraints(routing_brief))

        # ── Rhythm Instructions (ALL bypass_c08=True) ─────────────────────────
        rhythm_instructions = _build_rhythm_instructions(emotional_dna, routing_brief)

        # ── Assemble injection ─────────────────────────────────────────────────
        injection = BlockBInjection(
            adapter_slot=ADAPTER_SLOT,
            coach_id=coach_id,
            target=BlockTarget.BLOCK_B,
            section_header="## Psychological Routing Constraints (Adapter-4 — DEP-LIB-001 + DEP-ENG-016)",
            constraint_strings=constraints,
            rhythm_instructions=rhythm_instructions,
            metadata={
                "dep_lib_001": "DEP-LIB-001",
                "dep_eng_016": routing_brief.routing_id if routing_brief else None,
                "has_routing_brief": routing_brief is not None,
                "constraint_count": len(constraints),
                "rhythm_instruction_count": len(rhythm_instructions),
                "all_rhythm_bypass_c08": all(r.bypass_c08 for r in rhythm_instructions),
                "emotional_dna_confidence": getattr(
                    getattr(emotional_dna, "extraction_status", None),
                    "confidence",
                    None,
                ),
            },
        )

        # ── Receipt Write (FR47 DEP-ENG-041) ──────────────────────────────────
        entry = self._rc.log(
            agent_id=AGENT_ADAPTER,
            action=STAGE_ADAPTER,
            input_summary=(
                f"coach_id={coach_id} "
                f"routing_brief={'present' if routing_brief else 'absent'} "
                f"dep_lib_001_confidence="
                f"{getattr(getattr(emotional_dna, 'extraction_status', None), 'confidence', 'N/A')}"
            ),
            output_summary=(
                f"Block_B_constraints={len(constraints)} "
                f"rhythm_instructions={len(rhythm_instructions)} "
                f"all_bypass_c08={all(r.bypass_c08 for r in rhythm_instructions)}"
            ),
            metadata={
                "stage_name": STAGE_ADAPTER,
                "adapter_slot": ADAPTER_SLOT.value,
                "coach_id": coach_id,
                "dep_lib_001": "DEP-LIB-001",
                "has_routing_brief": routing_brief is not None,
                "constraint_count": len(constraints),
                "rhythm_instruction_count": len(rhythm_instructions),
                "c08_rhythm_whitelist_status": "ALL_WHITELISTED",
            },
        )

        return AdapterRunResult(
            adapter_slot=ADAPTER_SLOT,
            coach_id=coach_id,
            success=True,
            block_b=injection,
            receipt_id=entry.receipt_id,
            gate_failures=[],
            warnings=[],
        )

    def format_block_b_section(
        self,
        emotional_dna: EmotionalDNAProfile,
        coach_id: str,
        routing_brief: PsychRoutingBrief | None = None,
    ) -> str:
        """Produce the full Block B section text for SKILL.md injection.

        Returns:
            Multi-line string ready for SKILL.md Block B injection.
        """
        result = self.load(emotional_dna, coach_id, routing_brief)
        if result.block_b:
            return result.block_b.to_block_b_text()
        return ""
