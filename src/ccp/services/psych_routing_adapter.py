def _build_moral_foundation_constraints(profile: EmotionalDNAProfile) -> list[str]:
    """V6-V10 — MFQ-2 Moral Foundation activation directives.

    Only generates constraints for foundations with score > 6 (active axes)
    to avoid constraint bloat. Foundations scoring ≤ 6 are inactive for this coach.
    """
    constraints: list[str] = []
    mf = profile.moral_foundations
    ACTIVE_THRESHOLD = 0.6  # weight > 0.6 means this foundation is dominant for this coach

    foundation_map = [
        ("V6 — Care/Harm", mf.v6_care_harm,
         "Activate care/harm language — this audience is highly sensitive to "
         "suffering and protection narratives. Lead with who is being harmed."),
        ("V7 — Fairness/Cheating", mf.v7_fairness_cheating,
         "Fairness is a primary moral axis — use procedural and outcome-justice "
         "framing. This audience responds to 'the rules were broken' narratives."),
        ("V8 — Loyalty/Betrayal", mf.v8_loyalty_betrayal,
         "Loyalty is central — frame content around in-group belonging and "
         "betrayal costs. Tribal identity and covenant violations resonate deeply."),
        ("V9 — Authority/Subversion", mf.v9_authority_subversion,
         "Authority legitimacy matters — frame insights as grounded in expertise "
         "and earned credibility. Challenges to authority need strong warrant."),
        ("V10 — Sanctity/Degradation", mf.v10_sanctity_degradation,
         "Purity/sanctity is active — use language that protects what is valued "
         "as sacred. Contamination and defilement metaphors land with force."),
    ]

    for label, foundation_field, guidance in foundation_map:
        weight = getattr(foundation_field, "weight", 0.0) or 0.0
        if weight > ACTIVE_THRESHOLD:
            constraints.append(
                f"CONSTRAINT ({label}, weight={weight:.2f}): {guidance}"
            )

    # V10b liberty (if present)
    liberty_weight = getattr(getattr(mf, "v10b_liberty_oppression", None), "weight", 0.0) or 0.0
    if liberty_weight > ACTIVE_THRESHOLD:
        constraints.append(
            f"CONSTRAINT (V10b — Liberty/Oppression, weight={liberty_weight:.2f}): "
            f"Autonomy and freedom from coercion are primary concerns. "
            f"Frame content around reclaiming sovereignty and resisting constraint."
        )

    return constraints


def _build_csip_constraints(profile: EmotionalDNAProfile) -> list[str]:
    """CSIP v3 — Emotional ceiling/floor and suppression pattern constraints."""
    constraints: list[str] = []
    csip = profile.csip_v3_extensions

    # Emotional ceiling (per topic)
    ceiling_topics = getattr(csip.emotional_ceiling_per_topic, "topic_ceilings", [])
    if ceiling_topics:
        ceilings_str = "; ".join(
            f"{tc.topic}→{tc.max_ttt}" for tc in ceiling_topics[:5] if tc.max_ttt
        )
        if ceilings_str:
            constraints.append(
                f"CONSTRAINT (CSIP v3 — Emotional Ceilings): "
                f"Do not exceed topic emotional ceilings: {ceilings_str}. "
                f"Content above these ceilings triggers defensive shutdown."
            )

    # Emotional floor (per topic)
    floor_topics = getattr(csip.emotional_floor_per_topic, "topic_floors", [])
    if floor_topics:
        floors_str = "; ".join(
            f"{tf.topic}→{tf.min_ttt}" for tf in floor_topics[:5] if tf.min_ttt
        )
        if floors_str:
            constraints.append(
                f"CONSTRAINT (CSIP v3 — Emotional Floors): "
                f"Do not fall below topic emotional floors: {floors_str}. "
                f"Content below these floors reads as hollow to this audience."
            )

    # Suppression patterns
    suppression_patterns = getattr(csip.suppression_patterns, "patterns", [])
    if suppression_patterns:
        emotions_str = "; ".join(
            sp.emotion for sp in suppression_patterns[:5] if sp.emotion
        )
        if emotions_str:
            constraints.append(
                f"CONSTRAINT (CSIP v3 — Suppression Patterns): "
                f"This coach's audience suppresses these emotions: {emotions_str}. "
                f"Do not force emotional expression where suppression is protective."
            )

    # Resolution pattern
    resolution_dominant = getattr(csip.resolution_pattern, "dominant", None)
    if resolution_dominant:
        constraints.append(
            f"CONSTRAINT (CSIP v3 — Resolution Pattern [{resolution_dominant.value}]): "
            f"Structure emotional arc to match this coach's resolution style. "
            f"Do not close with resolution patterns that contradict this baseline."
        )

    return constraints


# ─── Rhythm Instruction Builders ──────────────────────────────────────────────

def _build_rhythm_instructions(
    profile: EmotionalDNAProfile,
    brief: PsychRoutingBrief | None,
) -> list[RhythmInstruction]:
    """Generate rhythm/pacing instructions from emotional DNA and routing brief.

    ALL produced instructions carry bypass_c08=True.
    FR8 §C-08: Rhythm instructions from the Psychological Routing Adapter
    are classified as Structural Mechanics and are WHITELISTED by C-08.

    This is non-negotiable. Never modify bypass_c08 to False on these objects.
    """
    instructions: list[RhythmInstruction] = []

    # V2-driven rhythm: appraisal sequence determines pacing
    v2_ordering = profile.appraisal_variables.v2_appraisal_sequence_ordering.type
    v2_val = v2_ordering.value if v2_ordering else "mixed"
    if v2_val == "mechanism_first":
        instructions.append(RhythmInstruction(
            instruction_text=(
                "RHYTHM (V2-driven): Build sentence rhythm to create analytical momentum — "
                "short declarative sentences to state the mechanism, longer sentences to "
                "unfold the consequence. Punctuation density should increase at the pivot."
            ),
            bypass_c08=True,
            source_variable="V2",
        ))
    elif v2_val == "narrative_first":
        instructions.append(RhythmInstruction(
            instruction_text=(
                "RHYTHM (V2-driven): Open with longer, immersive sentence structures "
                "to build narrative transportation. Transition to shorter, punchier "
                "sentences at the insight reveal. The rhythm mirrors the story arc."
            ),
            bypass_c08=True,
            source_variable="V2",
        ))
    elif v2_val in ("moral_verdict_first", "coping_first"):
        instructions.append(RhythmInstruction(
            instruction_text=(
                "RHYTHM (V2-driven): Open with a short, definitive sentence for the "
                "verdict or coping frame. Let subsequent sentences expand at natural pace. "
                "The opening must land with rhythmic authority — no subordinate clauses."
            ),
            bypass_c08=True,
            source_variable="V2",
        ))

    # V3-driven rhythm: coping ratio drives closing pace
    v3_ratio = profile.appraisal_variables.v3_coping_potential_pattern.ratio or 0.5
    if v3_ratio >= 0.7:
        instructions.append(RhythmInstruction(
            instruction_text=(
                "RHYTHM (V3-driven): Accelerate sentence pace in the closing section — "
                "shorter sentences build momentum toward the action frame. "
                "The rhythm should feel like it is pushing toward resolution."
            ),
            bypass_c08=True,
            source_variable="V3",
        ))

    # Routing brief arousal-driven rhythm
    if brief:
        arousal = brief.psychological_classification.arousal_direction.value
        if arousal == "lowers":
            instructions.append(RhythmInstruction(
                instruction_text=(
                    "RHYTHM (FR18 Arousal Direction — lowers): Reduce sentence rhythm intensity "
                    "progressively through the content. Longer sentences, fewer hard stops, "
                    "softer punctuation. The rhythm decelerates audience arousal."
                ),
                bypass_c08=True,
                source_variable="arousal_direction",
            ))
        elif arousal == "raises":
            instructions.append(RhythmInstruction(
                instruction_text=(
                    "RHYTHM (FR18 Arousal Direction — raises): Increase sentence rhythm intensity "
                    "progressively. Short punchy sentences, more hard stops, higher punctuation "
                    "density toward the close. The rhythm elevates audience arousal."
                ),
                bypass_c08=True,
                source_variable="arousal_direction",
            ))

    return instructions


