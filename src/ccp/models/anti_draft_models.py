"""
CCP FR22 — 3-Level Anti-Draft Intelligence Models (DEP-PROTO-013)

Pydantic v2 models for the Anti-Draft Calibration Protocol.
Every compiled SKILL.md receives a 3-level contrastive fence injected
before any positive instruction reaches the generation agent.

Spec reference: FR22_Anti_Draft_Intelligence_Tech_Spec.md
  §3 — Architecture Traceability (DEP-ENG-021[M3_UNDENIABLE], DEP-ENG-004)
  §4 — Stage 1: Level 1 Construction (Frozen Anchor — Block A Invariant Load)
  §4 — Stage 2: Level 2 Generation (Mode & M3 Synthesis)
  §4 — Stage 3: Level 3 Injection (Negative Space Load)
  §4 — Stage 4: Critic Subagent Enforcement Gate
  §5 — Primary Output Schema (anti_draft_deliberation_log.json)

Critical constraints:
  - Frozen Anchor Mandate: Level 1 MUST use a frozen, low-capability model
    (e.g., gpt-3.5-turbo). The primary model NEVER generates its own anchor.
  - Absolute First Load Order (M3 Mandate): DEP-ENG-004 (Level 3) MUST be
    loaded FIRST — before any positive instruction.
  - Gate PC-03: L3 array must contain >= 15 contrastive strings.
    Violation triggers L3_INSUFFICIENT_DEPTH halt.
  - Critic Gate: violations >= 2 → full purge + Pass 3 regenerate.
               violations == 1 → targeted section rewrite.
               violations == 0 → pass payload.

ADR-01: coach_id scopes all operations per tenant isolation mandate.
"""

