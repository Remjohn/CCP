# ─── Level 1: Frozen Anchor Block ─────────────────────────────────────────────

class Level1FrozenAnchor(BaseModel):
    """Level 1 Anti-Draft Block — Archetype Centroid Anchor.

    Spec §4 Stage 1: 'archetype's AI Cliché anchor is intentionally generated
    by a frozen, low-capability model (e.g., gpt-3.5-turbo) to permanently
    lock the statistical centroid.'

    Required subsections per spec §4 Stage 1 Step 2:
      [Statistical Centroid Prose Example]
      [Mechanism Failure Diagnosis]
      [Resolution Failure Diagnosis]
      [Semantic Distance Instruction]
    """

    frozen_model_used: str = Field(
        default=FROZEN_ANCHOR_MODEL,
        description="Spec: MUST be a frozen low-capability model, NEVER the primary model.",
    )
    statistical_centroid_prose: str = Field(
        default="",
        description=(
            "3-5 sentences of terrible AI cliché — concrete written prose. "
            "Spec §3 Technical Decision 1: NEVER a list of rules to avoid. "
            "Must be literal bad text acting as a negative semantic anchor."
        ),
    )
    mechanism_failure_diagnosis: str = Field(
        default="",
        description="Why generic AI fails mechanistically for this archetype.",
    )
    resolution_failure_diagnosis: str = Field(
        default="",
        description="Why generic AI's resolution structure fails emotionally.",
    )
    semantic_distance_instruction: str = Field(
        default="",
        description="Explicit instruction to maximise vector distance from this centroid.",
    )
    archetype_id: str = Field(
        default="",
        description="Archetype this anchor is locked to.",
    )
    receipt_hash: str = Field(
        default="",
        description="Cryptographic hash written to Receipt Chain Guard (DEP-ENG-041).",
    )

    def is_valid_prose(self) -> bool:
        """AC1 guard: Level 1 must be concrete prose, not abstract descriptions.

        Spec §8 AC1: Submitting Level 1 as 'Avoid clichés and generic tone.'
        results in immediate Block C Compilation failure.
        """
        prose = self.statistical_centroid_prose.strip()
        if not prose:
            return False
        # Count sentences (split on . ! ?)
        import re
        sentences = [s.strip() for s in re.split(r"[.!?]+", prose) if s.strip()]
        return len(sentences) >= L1_MINIMUM_PROSE_SENTENCES

    def has_all_subsections(self) -> bool:
        """Spec §4 Stage 1 Step 2: All 4 subsections must be populated."""
        return all([
            bool(self.statistical_centroid_prose.strip()),
            bool(self.mechanism_failure_diagnosis.strip()),
            bool(self.resolution_failure_diagnosis.strip()),
            bool(self.semantic_distance_instruction.strip()),
        ])


