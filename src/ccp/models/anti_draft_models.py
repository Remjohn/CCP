# ─── Critic Report ─────────────────────────────────────────────────────────────

class CriticViolation(BaseModel):
    """A single violation detected by the Critic Subagent.

    Spec §4 Stage 4: Each level scored independently.
    """

    violation_type: ViolationType
    level: AntiDraftLevel
    offending_text_excerpt: str = Field(
        default="",
        description="Excerpt from draft_v1.md that triggered the violation.",
    )
    forbidden_string_matched: Optional[str] = Field(
        default=None,
        description="The exact forbidden string matched (Level 3 violations).",
    )


class CriticReport(BaseModel):
    """Output of the Critic Subagent evaluation (Pass 2).

    Spec §4 Stage 4:
      - violations >= 2 → FULL_PURGE_REGENERATE (Pass 3).
      - violations == 1 → TARGETED_SECTION_REWRITE.
      - violations == 0 → PASS_GENERATION_PAYLOAD.

    AC4: 'Critic successfully spots 3 violations → halts, purges draft,
    restarts generation with critic_report.json as context.'
    Failure Example: Critic just logs them as warnings and passes the flawed script.
    """

    pass_evaluated: CriticPass = Field(
        default=CriticPass.PASS_1_INITIAL,
    )
    violations: list[CriticViolation] = Field(
        default_factory=list,
    )
    violation_count: int = Field(
        default=0,
        description="Total violation count — drives the verdict decision.",
    )
    verdict: CriticVerdict = Field(
        default=CriticVerdict.PASS_GENERATION_PAYLOAD,
    )
    targeted_rewrite_triggered: bool = Field(
        default=False,
    )
    full_purge_triggered: bool = Field(
        default=False,
    )
    context_window_truncated: bool = Field(
        default=False,
        description="Spec §4 Stage 4 Failure Condition: critic failed due to truncation.",
    )
    receipt_hash: str = Field(default="")

    def model_post_init(self, __context: Any) -> None:
        """Auto-derive verdict, violation_count, and triggered flags."""
        self.violation_count = len(self.violations)
        if self.violation_count >= CRITIC_FULL_PURGE_THRESHOLD:
            self.verdict = CriticVerdict.FULL_PURGE_REGENERATE
            self.full_purge_triggered = True
            self.targeted_rewrite_triggered = False
        elif self.violation_count == 1:
            self.verdict = CriticVerdict.TARGETED_SECTION_REWRITE
            self.targeted_rewrite_triggered = True
            self.full_purge_triggered = False
        else:
            self.verdict = CriticVerdict.PASS_GENERATION_PAYLOAD
            self.targeted_rewrite_triggered = False
            self.full_purge_triggered = False


# ─── Validation Pass Summary ────────────────────────────────────────────────────

class AntiDraftValidationPass(BaseModel):
    """Tracks which levels were successfully loaded/generated.

    Spec §5 Output Schema: anti_draft_deliberation_log.json
    'validation_pass' block.
    """

    level_1_archetype_loaded: bool = Field(default=False)
    level_2_mode_generated: bool = Field(default=False)
    level_3_negative_space_loaded: bool = Field(default=False)

    def all_loaded(self) -> bool:
        """All three levels must be present for a full anti-draft fence."""
        return (
            self.level_1_archetype_loaded
            and self.level_2_mode_generated
            and self.level_3_negative_space_loaded
        )


# ─── Deliberation Log (Primary Output) ─────────────────────────────────────────

class AntiDraftDeliberationLog(BaseModel):
    """Primary output schema for DEP-PROTO-013 execution metadata.

    Written alongside the Final Script as anti_draft_deliberation_log.json.
    Spec §5: Full schema including receipt_chain_hash, validation_pass,
    critic_evaluation, and final_semantic_distance_status.

    ADR-01: coach_id scopes the log for tenant isolation.
    """

    compilation_request_id: str = Field(
        ...,
        description="Unique compilation request identifier.",
    )
    coach_id: str = Field(
        ..., min_length=3, max_length=3,
        description="ADR-01 tenant isolation — 3-char coach acronym.",
    )
    receipt_chain_hash: str = Field(
        default="",
        description="Spec §5: Cryptographic hash from Receipt Chain Guard.",
    )
    validation_pass: AntiDraftValidationPass = Field(
        default_factory=AntiDraftValidationPass,
    )
    level_1_block: Optional[Level1FrozenAnchor] = Field(
        default=None,
        description="The frozen anchor block. None means FATAL HALT.",
    )
    level_2_block: Optional[Level2ModeBelief] = Field(
        default=None,
        description="Mode+M3 synthesis. None means FATAL HALT (unless degraded).",
    )
    level_3_block: Optional[ForbiddenVocabularyBlock] = Field(
        default=None,
        description="Forbidden strings block. None means FATAL HALT.",
    )
    critic_evaluation: Optional[CriticReport] = Field(
        default=None,
        description="Critic subagent report — populated after Pass 1.",
    )
    deliberation_override: bool = Field(
        default=False,
        description="True when supervisor manually overrides a failed check.",
    )
    final_semantic_distance_status: FinalSemanticDistanceStatus = Field(
        default=FinalSemanticDistanceStatus.FAILED,
    )
    halt_reason: Optional[AntiDraftHaltReason] = Field(
        default=None,
        description="Non-None if the pipeline halted at any stage.",
    )
    halted: bool = Field(
        default=False,
        description="True if a fatal halt was triggered.",
    )
    l2_degradation_reason: Optional[L2DegradationReason] = Field(
        default=None,
        description="Set when Level 2 runs in degraded mode (M3 absent).",
    )

    def model_post_init(self, __context: Any) -> None:
        """Auto-derive halted and final_semantic_distance_status."""
        self.halted = self.halt_reason is not None
        if not self.halted and self.validation_pass.all_loaded():
            critic = self.critic_evaluation
            if critic and critic.violation_count == 0:
                self.final_semantic_distance_status = FinalSemanticDistanceStatus.MAXIMIZED
            elif critic and critic.violation_count == 1:
                self.final_semantic_distance_status = FinalSemanticDistanceStatus.PARTIAL
            elif self.validation_pass.level_2_mode_generated and (
                self.level_2_block and self.level_2_block.is_degraded
            ):
                self.final_semantic_distance_status = FinalSemanticDistanceStatus.PARTIAL
